      const category = chooseCategoryColumn(categorical, visualConfig.categoryAliases);
      if (!category) return;
      aggregateCount(frame?.data ?? [], category).forEach((item) => {
        totals[item.name] = (totals[item.name] ?? 0) + item.value;
      });
